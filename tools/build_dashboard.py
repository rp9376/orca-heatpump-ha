# Heat only flows while the unit really produces it. The circulation pump keeps running
# between compressor runs, the valve rests on hot water when idle, and at a start the
# power reads 70 % for up to minutes before the unit reports that it is heating.
RUNNING: tuple[dict[str, Any], ...] = (
    {"entity": PUMP, "state": "on"},
    {"entity": OUTDOOR_STATE, "state_not": "off"},
    {"condition": "numeric_state", "entity": OUTDOOR_POWER, "above": 0},
)


def _svg(body: str) -> str:
    source = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" '
        f'fill="none">{body}</svg>'
    )
    return "data:image/svg+xml;base64," + base64.b64encode(source.encode()).decode()


def _base() -> str:
    """Return the diagram's boxes and idle pipes, readable on light and dark."""
    box = 'fill="#8882" stroke="#8886" stroke-width="2"'
    pipes = "".join(
        f'<path d="{d}" stroke="#8887" stroke-width="9" stroke-linecap="round" '
        'stroke-linejoin="round"/>'
        for d in (SUPPLY, HEATING_MAIN, FLOOR, RADIATORS, TANK, SOLAR_PIPE)
    )
    return _svg(
        '<defs><linearGradient id="t" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="#ff5252" stop-opacity=".55"/>'
        '<stop offset="1" stop-color="#42a5f5" stop-opacity=".45"/>'
        "</linearGradient></defs>"
        f"{pipes}"
        f'<rect x="40" y="200" width="180" height="200" rx="20" {box}/>'
        f'<rect x="620" y="40" width="340" height="130" rx="20" {box}/>'
        f'<rect x="620" y="185" width="340" height="130" rx="20" {box}/>'
        '<rect x="620" y="335" width="160" height="240" rx="44" fill="url(#t)" '
        'stroke="#8886" stroke-width="2"/>'
        f'<rect x="840" y="365" width="120" height="130" rx="20" {box}/>'
        '<circle cx="400" cy="300" r="26" fill="#8883" stroke="#8886" stroke-width="2"/>'
        '<circle cx="520" cy="110" r="26" fill="#8883" stroke="#8886" stroke-width="2"/>'
    )


def _flow(path: str, color: str) -> str:
    """Return an image of water moving along a pipe."""
    return _svg(
        f'<path d="{path}" stroke="{color}" stroke-width="9" stroke-linecap="round" '
        'stroke-linejoin="round" stroke-dasharray="4 22">'
        '<animate attributeName="stroke-dashoffset" from="26" to="0" dur=".9s" '
        'repeatCount="indefinite"/></path>'
    )


def _stub(path: str) -> str:
    """Return a solid piece of pipe showing which way the valve points.

    Neutral, because the valve's position says nothing about heat.
    """
    return _svg(
        f'<path d="{path}" stroke="#9e9e9e" stroke-width="9" stroke-linecap="round"/>'
    )


def _spin() -> str:
    """Return a ring turning around the outdoor unit's fan while it runs."""
    return _svg(
        '<circle cx="130" cy="262" r="46" stroke="#ff7043" stroke-width="5" '
        'stroke-dasharray="48 24" stroke-linecap="round">'
        '<animateTransform attributeName="transform" type="rotate" '
        'from="0 130 262" to="360 130 262" dur="2.4s" repeatCount="indefinite"/>'
        "</circle>"
    )


def _position(x: float, y: float) -> dict[str, str]:
    return {"left": f"{x / WIDTH:.1%}", "top": f"{y / HEIGHT:.1%}"}


def _overlay(image: str, *conditions: dict[str, Any]) -> dict[str, Any]:
    return {
        "type": "conditional",
        "conditions": list(conditions),
        "elements": [
            {
                "type": "image",
                "image": image,
                "tap_action": {"action": "none"},
                "hold_action": {"action": "none"},
                "style": {
                    "left": "50%",
                    "top": "50%",
                    "width": "100%",
                    "pointer-events": "none",
                },
            }
        ],
    }


def _label(
    entity: str,
    x: float,
    y: float,
    *,
    size: str = "clamp(12px, 1.5vw, 18px)",
    weight: int = 600,
    **options: str,
) -> dict[str, Any]:
    return {
        "type": "state-label",
        "entity": entity,
        **options,
        "style": _position(x, y)
        | {
            "color": "var(--primary-text-color)",
            "font-size": size,
            "font-weight": str(weight),
            "white-space": "nowrap",
            "padding": "0",
        },
    }


def _small(entity: str, x: float, y: float, **options: str) -> dict[str, Any]:
    return _label(entity, x, y, size="clamp(10px, 1.1vw, 14px)", weight=400, **options)


def _name(entity: str, x: float, y: float) -> dict[str, Any]:
    return _small(entity, x, y, attribute="friendly_name")


def _icon(icon: str, entity: str, x: float, y: float, color: str) -> dict[str, Any]:
    return {
        "type": "icon",
        "icon": icon,
        "entity": entity,
        "tap_action": {"action": "more-info"},
        "style": _position(x, y)
        | {"color": color, "--mdc-icon-size": "clamp(20px, 2.8vw, 36px)"},
    }


def _heat_flow(path: str, *conditions: dict[str, Any]) -> list[dict[str, Any]]:
    """Return a pipe's overlays: orange while heating, blue while cooling."""
    return [
        _overlay(
            _flow(path, HOT),
            *RUNNING,
            *conditions,
            {"entity": OUTDOOR_STATE, "state_not": "cooling"},
        ),
        _overlay(
            _flow(path, COLD),
            *RUNNING,
            *conditions,
            {"entity": OUTDOOR_STATE, "state": "cooling"},
        ),
    ]


