def _tile(entity: str, **options: Any) -> dict[str, Any]:
    # The entity's own name: the device's would cut every name off in a narrow tile.
    return {"type": "tile", "entity": entity, "name": {"type": "entity"}, **options}


def _main_tile(entity: str, **options: Any) -> dict[str, Any]:
    return {
        "type": "tile",
        "entity": entity,
        "grid_options": {"columns": "full"},
        **options,
    }


def _trend(entity: str, **options: Any) -> dict[str, Any]:
    return _tile(
        entity,
        features=[{"type": "trend-graph"}],
        **({"grid_options": {"columns": 6, "rows": 2}} | options),
    )


def _gauge(
    entity: str, name: str, low: int, high: int, segments: list[dict[str, Any]]
) -> dict[str, Any]:
    return {
        "type": "gauge",
        "entity": entity,
        "name": name,
        "min": low,
        "max": high,
        "needle": True,
        "segments": segments,
        "grid_options": {"columns": 6, "rows": 3},
    }


def _section(
    heading: str, icon: str, *cards: dict[str, Any], **options: Any
) -> dict[str, Any]:
    return {
        "type": "grid",
        **options,
        "cards": [
            {"type": "heading", "heading": heading, "icon": icon},
            *cards,
        ],
    }


