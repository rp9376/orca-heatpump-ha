def build(language: str) -> str:
    """Return a dashboard as YAML, with its header."""
    text = TEXT[language]
    config = {"title": text["title"], "views": [_overview(text), _trends(text)]}
    return HEADER + yaml.safe_dump(
        config, sort_keys=False, allow_unicode=True, width=88
    )


def main() -> None:
    """Write the dashboards."""
    DIRECTORY.mkdir(exist_ok=True)
    for language, name in FILES.items():
        path = DIRECTORY / name
        path.write_text(build(language), encoding="utf-8")
        print(f"{path}: {path.stat().st_size} bytes")


if __name__ == "__main__":
    main()
